const { chromium } = require('../node_modules/playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--disable-background-networking'] });
  const context = await browser.newContext({ offline: true, viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [], external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) external.push(r.url()); });
  const url = pathToFileURL(path.join(__dirname, 'index.html')).href;
  try {
    await page.goto(url);
    await page.locator('.card').first().waitFor();
    await page.waitForTimeout(200);
    assert.equal(await page.locator('.card').count(), 6);
    await page.screenshot({ path: path.join(__dirname, 'preview.png'), fullPage: true, animations: 'disabled' });
    const title = await page.locator('#editor-title').textContent();
    await page.getByRole('button', { name: 'Play I see you.', exact: true }).click();
    assert.equal(await page.locator('#now-title').textContent(), 'I see you.');
    assert.equal(await page.locator('#editor-title').textContent(), title);
    await page.locator('[data-word="0"]').click();
    await page.locator('[data-word="3"]').click({ modifiers: ['Shift'] });
    assert.equal(await page.locator('#range-start').textContent(), '0:00.70');
    assert.equal(await page.locator('#range-end').textContent(), '0:02.30');
    await page.locator('#zoom-in').click();
    assert.match(await page.locator('#editor-svg').getAttribute('viewBox'), /400/);
    await page.locator('#wave-fit').click();
    const box = await page.locator('#clip-wave').boundingBox();
    await page.mouse.move(box.x + box.width * .32, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .67, box.y + box.height / 2, { steps: 8 });
    await page.mouse.up();
    assert.match(await page.locator('#range-start').textContent(), /0:03\./);
    await page.locator('#crop').click();
    assert.match(await page.locator('#editor-title').textContent(), /crop/);
    assert.equal(await page.locator('#draft-history option').count(), 4);
    await page.locator('#keep').click();
    assert.equal(await page.locator('#draft-tag').textContent(), 'KEPT');
    await page.locator('.sidebar [data-view="recording"]').click();
    await page.locator('#capture-toggle').click();
    await page.locator('#capture-toggle').click();
    assert.match(await page.locator('#record-status').textContent(), /retained/);
    await page.locator('#jump-back').click();
    assert.match(await page.locator('#history-offset').textContent(), /10 seconds behind/);
    await page.locator('.sidebar [data-view="sentences"]').click();
    assert.equal(await page.locator('.piece.missing').count(), 1);
    await page.locator('.piece.missing').click();
    assert.match(await page.locator('.piece.missing').textContent(), /BLEEP/);
    await page.locator('#sentence-input').fill('I can see you');
    assert.equal(await page.locator('.piece.missing').count(), 0);
    const voiceBefore = await page.locator('.piece small').first().textContent();
    await page.locator('#shuffle').click();
    assert.notEqual(await page.locator('.piece small').first().textContent(), voiceBefore);
    await page.locator('[data-piece="0"]').dragTo(page.locator('[data-piece="3"]'));
    assert.equal(await page.locator('#sentence-input').inputValue(), 'can see you I');
    await page.locator('#laugh').click();
    await page.locator('#sentence-keep').click();
    assert.equal(await page.locator('.saved').count(), 3);
    await page.screenshot({ path: path.join(__dirname, 'sentences.png'), fullPage: true, animations: 'disabled' });
    await page.locator('.sidebar [data-view="palette"]').click();
    await page.locator('#performance').click();
    await page.locator('[data-palette="I"]').click();
    await page.locator('[data-palette="can"]').click();
    await page.locator('#performance').click();
    assert.equal(await page.locator('#sentence-input').inputValue(), 'I can');
    await page.locator('#settings-open').click();
    await page.locator('#layout').selectOption('tabs');
    await page.locator('#settings-close').click();
    assert.equal(await page.locator('.tabs').isVisible(), true);
    await page.locator('.tabs [data-view="board"]').click();
    await page.locator('#search-input').fill('Mara');
    assert.equal(await page.locator('.card').count(), 2);
    await page.locator('#search-input').fill('');
    await page.locator('#panic').click();
    assert.match(await page.locator('#panic').textContent(), /Resume guests/);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.locator('.card').first().waitFor();
    await page.waitForTimeout(200);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(overflow, false, 'phone layout must not overflow horizontally');
    await page.screenshot({ path: path.join(__dirname, 'phone.png'), fullPage: true });
    assert.deepEqual(errors, [], 'no JavaScript errors');
    assert.deepEqual(external, [], 'no external network requests');
    assert.equal(await page.evaluate(() => new Set([...document.querySelectorAll('[id]')].map(e => e.id)).size === document.querySelectorAll('[id]').length), true, 'unique element IDs');
    console.log('PASS: file:// offline load; board/editor isolation; word selection; crop/Keep; recording history; missing-word controls; sentence matching, shuffle and drag; performance-to-sentence; navigation styles; search; Panic; phone layout; no JavaScript errors or external requests.');
  } finally {
    await browser.close();
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
